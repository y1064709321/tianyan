/**
 * 题材关键词过滤 —— 扫榜抓回综合榜后, 用它把"跟本项目题材无关"的书剔掉。
 *
 * 单独成文件的原因: 这段逻辑是**纯函数**, 且有明确的对错样本 (见 scripts/test-genre-filter.js)。
 * 塞在 runner.ts 的函数内部就没法被测试引用, 每次调参只能靠"跑一遍扫榜看顺不顺眼",
 * 于是历史上改了三次都没改对 (单字关键词把赘婿文判成仙侠 / 收紧过头把真仙侠书误杀)。
 *
 * 【核心原则: 书名和简介用两套词, 严宽不同】
 * - 简介是 80~200 字长文本, 什么字都可能出现 → 一律只认**双字以上**词, 一个单字都不要。
 *   旧表混了单字 ("仙"/"剑"/"道"/"医"/"星"/"爱"/"甜"/"虐"), 命中率宽到离谱 —— 实测
 *   《极品全才神婿》这种都市赘婿文因为简介里带个"道"字就被判成仙侠, 混进"已按东方仙侠过滤"
 *   的结果里。用户当场发现"番茄的数据不对", 一半的锅在这里。
 * - 书名通常只有 3~8 字, 又不能一刀切: 《没钱修什么仙？》里没有"修仙"连续两字, 却确实是仙侠,
 *   全砍掉就误杀真书 → 书名额外允许一组**强特征单字**。
 * - 强特征单字只收"几乎不会被别的题材蹭到"的字 (仙/侠/魔/婿)。别往里塞 "道"/"医"/"星"/"爱"/
 *   "甜" 这种万能字 —— 塞了就回到被误判的老路。
 *
 * 宁可过滤后命中少 (没命中会走"全量 + 如实标注偏离"分支), 也不要把错的当对的。
 */

