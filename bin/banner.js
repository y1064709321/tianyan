// ============================================================
// 「天衍」像素招牌
// ------------------------------------------------------------
// 做法: 用系统黑体(SimHei) 28px 渲染 → 降采样成 28x28 点阵 → 用块字符
// (█ 全块 / ▀ 上半块 / ▄ 下半块) 每两个像素压成一个字符, 抵消终端字符
// 约 1:2 的宽高比。共 12 行 x 58 列。
//
// 想换字别手绘 —— 手绘的汉字基本认不出来。用 canvas 渲染新字再阈值化:
//   font = '28px SimHei'; 降采样到 28x28; 亮度 > 95 记为亮点
//
// 注意: 这份与 src/index.ts 里的 BANNER_LINES 必须保持一致 (同一个招牌,
// 一处是 bin 的欢迎屏, 一处是服务启动后的信息屏)。
// ============================================================

export const BANNER_LINES = [
  "   ████████████████████           ▄██   ▀██▄  ▄▄▄▄▄▄▄▄",
  "            ██                   ██▀      ▀█▀ ▀▀▀▀▀▀▀▀",
  "            ██                 ▄█▀  ▄",
  "            ██                     ▄██ ▄█▄   ▄▄▄▄▄▄▄▄▄▄",
  " ████████████████████████         ▄█▀   ▀██▀ ▀▀▀▀▀██▀▀▀",
  "           ████                 ▄███              ██",
  "          ▄████▄               ██▀██      ▄       ██",
  "         ▄██  ▀██                 ██      ██      ██",
  "        ███▀   ▀██▄               ██     ██       ██",
  "     ▄███▀       ▀██▄▄            ██    ██▀       ██",
  "  ▄▄███▀           ▀███▄▄▄        ██   ██▀        ██",
  "▀██▀▀                 ▀▀▀         ██   ▀▀      ████▀",
];

/** 招牌宽度 (列) —— 终端比这还窄就自动退回单行, 别硬塞折行糊成一团 */
export const BANNER_WIDTH = 58;

/**
 * 打印像素招牌
 * @param {(s: string) => string} colorFn 上色函数, 如 (s) => c("cyan", s)
 * @param {string} subtitle 副标题; 传 "" 则不打印
 */
export function printBanner(colorFn = (s) => s, subtitle = "多 Agent 协同创作系统   · 7 步流水线") {
  const width = process.stdout.columns || 80;
  if (width >= BANNER_WIDTH + 4) {
    BANNER_LINES.forEach((line) => console.log(colorFn(line)));
    if (subtitle) console.log(`\n   ${colorFn(subtitle)}\n`);
  } else {
    console.log(`\n  ${colorFn("✦  天  衍  ✦")}${subtitle ? "  " + subtitle : ""}\n`);
  }
}
